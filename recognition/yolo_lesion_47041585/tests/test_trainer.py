from collections import Counter
from pathlib import Path
from typing import Any, Literal

import numpy as np
import pytest
from PIL import Image

from tests.factories import make_records
from yolo_lesion_47041585.dataset import EpochSampler, SplitRecord
from yolo_lesion_47041585.modules import LesionDetectionTrainer

EPOCHS = 2


def write_dataset(root: Path, records: list[SplitRecord]) -> Path:
    """Write the records as a YOLO dataset of tiny noise images, plus a small val split."""
    rng = np.random.default_rng(0)
    items = {
        "train": [(r.audited.record.isic_id, r.audited.record.class_id) for r in records],
        "val": [(f"VAL_{i:02d}", i % 2) for i in range(8)],
    }
    for split, entries in items.items():
        (root / "images" / split).mkdir(parents=True)
        (root / "labels" / split).mkdir(parents=True)
        for isic_id, class_id in entries:
            noise = rng.integers(0, 255, (64, 64, 3), dtype=np.uint8)
            Image.fromarray(noise).save(root / "images" / split / f"{isic_id}.jpg")
            (root / "labels" / split / f"{isic_id}.txt").write_text(
                f"{class_id} 0.5 0.5 0.4 0.4\n"
            )
    yaml_path = root / "dataset.yaml"
    yaml_path.write_text(
        f"path: {root}\ntrain: images/train\nval: images/val\n"
        "names:\n  0: Benign\n  1: Malignant\n"
    )
    return yaml_path


def make_trainer(
    root: Path,
    records: list[SplitRecord],
    scheme: Literal["stock", "replacement"],
    target_fraction: float | None,
    workers: int,
) -> LesionDetectionTrainer:
    return LesionDetectionTrainer(
        overrides=dict(
            model="yolo11n.yaml",  # built from the config, so no weights are downloaded
            data=str(write_dataset(root / "data", records)),
            epochs=EPOCHS,
            imgsz=64,
            batch=8,
            workers=workers,
            device="cpu",
            amp=False,
            plots=False,
            verbose=False,
            mosaic=0.0,
            seed=7,
            project=str(root / "runs"),
            name="run",
        ),
        train_records=records,
        scheme=scheme,
        target_fraction=target_fraction,
    )


@pytest.mark.parametrize(
    "workers, target_fraction", [(0, 0.5), (2, 0.5), (0, None)]  # None is the A0 case
)
def test_training_uses_the_sampler_draws(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    workers: int,
    target_fraction: float | None,
):
    """Each epoch trains on exactly the images the sampler drew, with a fixed length."""
    records = make_records(24, 6)
    ids = [r.audited.record.isic_id for r in records]

    draws: list[list[str]] = []
    original = EpochSampler.__iter__

    def recording_iter(self: EpochSampler):
        epoch_draws = list(original(self))
        draws.append([ids[i] for i in epoch_draws])
        return iter(epoch_draws)

    monkeypatch.setattr(EpochSampler, "__iter__", recording_iter)

    trainer = make_trainer(tmp_path, records, "replacement", target_fraction, workers)
    trained_on: dict[int, list[str]] = {}
    untyped: Any = trainer  # Ultralytics' trainer attributes are untyped
    preprocess = untyped.preprocess_batch

    def recording_preprocess(batch: dict[str, Any]) -> Any:
        trained_on.setdefault(int(untyped.epoch), []).extend(
            Path(file).stem for file in batch["im_file"]
        )
        return preprocess(batch)

    monkeypatch.setattr(trainer, "preprocess_batch", recording_preprocess)
    trainer.train()

    assert len(draws) >= EPOCHS
    assert draws[0] != draws[1]
    for epoch in range(EPOCHS):
        assert len(draws[epoch]) == len(records)
        assert Counter(trained_on[epoch]) == Counter(draws[epoch])


def test_stock_scheme_keeps_the_stock_loader(tmp_path: Path):
    trainer = make_trainer(tmp_path, make_records(24, 6), "stock", None, workers=0)
    trainer.train()
    assert trainer.train_sampler is None


def test_mismatched_training_images_are_rejected(tmp_path: Path):
    records = make_records(24, 6)
    trainer = make_trainer(tmp_path, records, "replacement", 0.5, workers=0)
    trainer._weight_by_id = {"ISIC_9999": 1.0}  # pyright: ignore[reportPrivateUsage]
    with pytest.raises(ValueError, match="do not match"):
        trainer.train()


def test_stock_scheme_rejects_a_target_fraction(tmp_path: Path):
    with pytest.raises(ValueError):
        make_trainer(tmp_path, make_records(24, 6), "stock", 0.5, workers=0)
