def write_dataset(root: Path, train_classes: dict[str, int]) -> Path:
    """Write a YOLO dataset of tiny noise images, plus a small val split."""
    rng = np.random.default_rng(0)
    items = {
        "train": list(train_classes.items()),
        "val": [(f"VAL_{i:02d}", i % 2) for i in range(8)],
    }
    for split, entries in items.items():
        (root / "images" / split).mkdir(parents=True)
        (root / "labels" / split).mkdir(parents=True)
        for isic_id, class_id in entries:
            noise = rng.integers(0, 255, (64, 64, 3), dtype=np.uint8)
            Image.fromarray(noise).save(root / "images" / split / f"{isic_id}.jpg")
            (root / "labels" / split / f"{isic_id}.txt").write_text(
                f"{class_id} 0.5 0.5 0.4 0.4\n"
            )
    yaml_path = root / "dataset.yaml"
    yaml_path.write_text(
        f"path: {root}\ntrain: images/train\nval: images/val\n"
        "names:\n  0: Benign\n  1: Malignant\n"
    )
    return yaml_path


def make_trainer(
    root: Path,
    classes: dict[str, int],
    scheme: Literal["stock", "replacement"],
    target_fraction: float | None,
    workers: int = 0,
    given_classes: dict[str, int] | None = None,
) -> LesionDetectionTrainer:
    """A trainer on a dataset of `classes`; `given_classes` overrides what it is told."""
    return LesionDetectionTrainer(
        overrides=dict(
            model="yolo11n.yaml",  # built from the config, so no weights are downloaded
            data=str(write_dataset(root / "data", classes)),
            epochs=EPOCHS,
            imgsz=64,
            batch=8,
            workers=workers,
            device="cpu",
            amp=False,
            plots=False,
            verbose=False,
            mosaic=0.0,
            seed=7,
            project=str(root / "runs"),
            name="run",
        ),
        train_classes=classes if given_classes is None else given_classes,
        scheme=scheme,
        target_fraction=target_fraction,
    )


@pytest.mark.parametrize(
    "workers, target_fraction",
    [(0, 0.5), (2, 0.5), (0, None)],  # None is the A0 case
)
def test_training_uses_the_sampler_draws(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    workers: int,
    target_fraction: float | None,
):
    """Each epoch trains on exactly the images the sampler drew, with a fixed length."""
    classes = make_classes(24, 6)
    ids = list(classes)
    trainer = make_trainer(tmp_path, classes, "replacement", target_fraction, workers)

    trained_on: dict[int, list[str]] = {}
    untyped: Any = trainer  # Ultralytics' trainer attributes are untyped
    preprocess = untyped.preprocess_batch

    def recording_preprocess(batch: dict[str, Any]) -> Any:
        trained_on.setdefault(int(untyped.epoch), []).extend(
            Path(file).stem for file in batch["im_file"]
        )
        return preprocess(batch)

    monkeypatch.setattr(trainer, "preprocess_batch", recording_preprocess)
    trainer.train()

    assert trainer.train_sampler is not None and trainer.train_class_ids is not None
    history = trainer.train_sampler.history
    assert len(history) >= EPOCHS
    assert not np.array_equal(history[0], history[1])
    for epoch in range(EPOCHS):
        # the sampler indexes images in dataset order, which is sorted by file name
        indices: list[int] = history[epoch].tolist()
        drawn = [ids[i] for i in indices]
        assert len(drawn) == len(classes)
        assert Counter(trained_on[epoch]) == Counter(drawn)


