def test_best_checkpoint_follows_map50_95_and_keeps_the_earliest_tie(tmp_path: Path):
    """Epochs score by mAP50:95 alone, and an exact tie does not replace the best."""
    trainer = make_trainer(tmp_path, make_classes(24, 6), "stock", None)
    untyped: Any = trainer
    scores = iter([0.10, 0.30, 0.30, 0.20])

    def fake_validator(_: object) -> dict[str, float]:
        return {
            MAP_50_95: next(scores),
            "metrics/mAP50(B)": 0.99,  # Ultralytics would weight this at 10%
            "fitness": 0.99,
        }

    untyped.validator = fake_validator

    results = [trainer.validate() for _ in range(4)]
    fitness = [f for _, f in results]

    assert fitness[0] == 0.10 and fitness[1] == 0.30  # each a new best
    assert untyped.best_fitness == 0.30
    assert fitness[2] is not None and fitness[2] < untyped.best_fitness  # tie loses
    assert fitness[3] == 0.20
    assert all(m is not None and "fitness" not in m for m, _ in results)


def test_trainer_overrides_flatten_the_resolved_config(tmp_path: Path):
    config = resolve_training_config([CONFIGS / "base.yaml", CONFIGS / "o35.yaml"])
    run_dir = tmp_path / "runs" / "O35-47041585"
    overrides = trainer_overrides(config, tmp_path / "yolo11n.pt", run_dir)

    assert overrides["model"] == str(tmp_path / "yolo11n.pt")
    assert overrides["name"] == "O35-47041585"
    assert overrides["project"] == str(run_dir.parent.resolve())
    assert overrides["optimizer"] == "AdamW" and overrides["batch"] == 16
    assert overrides["flipud"] == 0.5 and overrides["mosaic"] == 0.0
    assert overrides["seed"] == 47041585
    assert "sampling" not in overrides and "scheme" not in overrides


def training_item(condition: str, root: Path) -> Callable[[], dict[str, Any]]:
    """A function returning the first training item of `condition`'s real pipeline."""
    config = resolve_training_config([CONFIGS / "base.yaml", CONFIGS / f"{condition}.yaml"])
    config["data"] = write_dataset(root / condition, make_classes(8, 2))
    config["train"].update(imgsz=64, batch=8, workers=0)
    overrides = trainer_overrides(config, root / "m.pt", root / "runs" / "r")
    # Ultralytics' config and dataset builders are untyped
    cfg: Any = get_cfg(overrides=overrides)
    build: Any = build_yolo_dataset  # pyright: ignore[reportUnknownVariableType]
    dataset: Any = build(
        cfg, str(root / condition / "images" / "train"), 8,
        check_det_dataset(str(config["data"])), mode="train", stride=32,
    )  # fmt: skip

    def first_item() -> dict[str, Any]:
        return dataset[0]

    return first_item


def test_b0_has_no_random_augmentation_and_a0_does(tmp_path: Path):
    """The same image comes out identical under B0 but varies under A0."""
    b0, a0 = training_item("b0", tmp_path), training_item("a0", tmp_path)

    first = b0()
    for _ in range(10):
        again = b0()
        assert torch.equal(first["img"], again["img"])
        assert torch.equal(first["bboxes"], again["bboxes"])

    original = a0()
    assert any(not torch.equal(original["img"], a0()["img"]) for _ in range(10))


def test_detector_checks(tmp_path: Path):
    """A detection checkpoint loads, and a model must have the project's classes."""
    path = tmp_path / "detector.pt"
    YOLO("yolo11n.yaml").save(path)  # built from the config, so no download

    model = build_detector(str(path))
    with pytest.raises(ValueError):
        validate_model_contract(model, ["Benign", "Malignant"])  # 80 COCO classes
    names = list(model.names.values())
    validate_model_contract(model, names)  # passes against its own class names
