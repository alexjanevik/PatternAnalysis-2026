from pathlib import Path

import numpy as np
import pytest

from yolo_lesion_47041585.dataset import (
    AuditedRecord,
    CohortRecord,
    EpochSampler,
    NormalizedBox,
    Split,
    SplitRecord,
    build_sampling_weights,
)


def make_records(
    benign: int, malignant: int, split: Split = "train"
) -> list[SplitRecord]:
    records: list[SplitRecord] = []
    for index in range(benign + malignant):
        is_malignant = index >= benign
        isic_id = f"ISIC_{index:04d}"
        cohort_record = CohortRecord(
            isic_id=isic_id,
            source_set="train",
            image_path=Path(f"{isic_id}.jpg"),
            mask_path=Path(f"{isic_id}.png"),
            patient_id=f"P{index}",
            lesion_id=None,
            diagnosis="Malignant" if is_malignant else "Benign",
            class_id=1 if is_malignant else 0,
        )
        audited = AuditedRecord(
            record=cohort_record,
            image_width=100,
            image_height=100,
            box=NormalizedBox(0.5, 0.5, 0.5, 0.5),
            image_sha256="",
            mask_sha256="",
        )
        records.append(SplitRecord(audited, group_id=f"G{index}", split=split))
    return records


def test_natural_weights_are_uniform():
    weights = build_sampling_weights(make_records(8, 2), None)
    assert weights == pytest.approx(np.full(10, 0.1))


@pytest.mark.parametrize("target", [0.35, 0.5])
def test_target_fraction_sets_the_malignant_probability_mass(target: float):
    records = make_records(80, 20)
    weights = build_sampling_weights(records, target)
    assert weights.sum() == pytest.approx(1)
    assert weights[80:].sum() == pytest.approx(target)  # malignant records come last
    assert len(set(weights[:80])) == 1 and len(set(weights[80:])) == 1


@pytest.mark.parametrize("target", [0.0, 1.0, -0.1, 1.5])
def test_target_fraction_must_be_strictly_between_zero_and_one(target: float):
    with pytest.raises(ValueError):
        build_sampling_weights(make_records(8, 2), target)


def test_a_target_needs_both_classes():
    with pytest.raises(ValueError):
        build_sampling_weights(make_records(10, 0), 0.5)
    with pytest.raises(ValueError):
        build_sampling_weights(make_records(0, 10), 0.5)


def test_only_training_records_can_be_sampled():
    with pytest.raises(ValueError):
        build_sampling_weights(make_records(8, 2, split="val"), 0.5)


def test_epoch_length_is_fixed():
    """Draw count equals the requested length regardless of the weights."""
    for target in (None, 0.35, 0.5):
        weights = build_sampling_weights(make_records(80, 20), target)
        sampler = EpochSampler(weights, length=100, seed=1)
        assert len(sampler) == 100
        assert len(list(sampler)) == 100


def test_draws_are_valid_indices():
    sampler = EpochSampler(build_sampling_weights(make_records(8, 2), 0.5), 500, 1)
    assert all(0 <= index < 10 for index in sampler)


@pytest.mark.parametrize("target", [0.35, 0.5])
def test_malignant_fraction_is_close_to_target(target: float):
    """Allow stochastic variation; do not assert exact proportions."""
    weights = build_sampling_weights(make_records(80, 20), target)
    draws = list(EpochSampler(weights, length=20_000, seed=1))
    fraction = sum(index >= 80 for index in draws) / len(draws)
    assert fraction == pytest.approx(target, abs=0.02)


def test_epochs_differ_but_are_reproducible():
    """set_epoch(n) gives the same draws every time but different draws per epoch."""
    weights = build_sampling_weights(make_records(80, 20), 0.5)
    sampler = EpochSampler(weights, length=200, seed=1)

    sampler.set_epoch(0)
    first = list(sampler)
    sampler.set_epoch(1)
    second = list(sampler)
    sampler.set_epoch(0)
    again = list(sampler)

    assert first == again
    assert first != second


def test_different_seeds_give_different_draws():
    weights = build_sampling_weights(make_records(80, 20), 0.5)
    assert list(EpochSampler(weights, 200, seed=1)) != list(
        EpochSampler(weights, 200, seed=2)
    )


def test_iterating_twice_without_set_epoch_repeats_the_epoch():
    sampler = EpochSampler(build_sampling_weights(make_records(8, 2), None), 50, 1)
    assert list(sampler) == list(sampler)


def test_invalid_sampler_arguments_are_rejected():
    with pytest.raises(ValueError):
        EpochSampler(np.array([0.5, 0.2]), 10, 1)  # does not sum to 1
    with pytest.raises(ValueError):
        EpochSampler(np.array([1.5, -0.5]), 10, 1)  # negative weight
    with pytest.raises(ValueError):
        EpochSampler(np.array([0.5, 0.5]), 0, 1)  # empty epoch
