from PIL import Image

from yolo_lesion_47041585.dataset import NormalizedBox
from yolo_lesion_47041585.helpers.visualisation import draw_detections
from yolo_lesion_47041585.predict import Detection

MALIGNANT_RED = (214, 39, 40)


def test_boxes_are_drawn_in_the_original_image_frame_without_changing_it():
    image = Image.new("RGB", (200, 100))  # not square, so x and y can't be mixed up
    detection = Detection("ISIC_1", NormalizedBox(0.5, 0.5, 0.5, 0.5), 1, 0.9)

    drawn = draw_detections(image, [detection], ["Benign", "Malignant"])

    # the box spans x 50-150 and y 25-75 on a 200x100 image
    assert drawn.getpixel((50, 50)) == MALIGNANT_RED  # left edge
    assert drawn.getpixel((100, 25)) == MALIGNANT_RED  # top edge
    assert drawn.getpixel((100, 50)) == (0, 0, 0)  # inside is untouched
    assert image.getpixel((50, 50)) == (0, 0, 0)  # the input was copied, not drawn on
