def test_an_infeasible_model_keeps_both_alternatives():
    table = [point(0.72, 0.29), point(0.60, 0.10), point(0.91, 0.70), point(0.95, 0.90)]
    selection = select_operating_point(table)

    assert selection.status == "infeasible" and not selection.meets_stretch
    assert selection.workload_alternative == point(0.72, 0.29)  # best m within b <= 0.30
    assert selection.sensitivity_alternative == point(0.91, 0.70)  # lowest b with m >= 0.90
    # the primary follows the workload constraint first, and is labelled as failing
    assert selection.primary == point(0.72, 0.29) and selection.basis == "workload_constrained"


def test_the_fallbacks_when_a_constraint_cannot_be_met_at_all():
    no_workload = select_operating_point([point(0.95, 0.60), point(0.91, 0.40)])
    assert no_workload.workload_alternative is None
    assert (no_workload.basis, no_workload.primary) == ("sensitivity_constrained", point(0.91, 0.40))

    neither = select_operating_point([point(0.50, 0.40), point(0.60, 0.45), point(0.60, 0.42)])
    assert neither.workload_alternative is None and neither.sensitivity_alternative is None
    assert (neither.basis, neither.primary) == ("maximum_sensitivity", point(0.60, 0.42))


