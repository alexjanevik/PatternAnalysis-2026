def random_data(seed: int) -> tuple[list[Detection], list[Detection]]:
    rng = np.random.default_rng(seed)
    preds: list[Detection] = []
    truths: list[Detection] = []
    for index in range(60):
        image = f"I{index:02d}"
        truths.append(truth(int(index % 3 == 0), image))
        for _ in range(int(rng.integers(0, 5))):
            box = NormalizedBox(*rng.uniform(0.3, 0.7, 2), *rng.uniform(0.25, 0.5, 2))
            preds.append(det(int(rng.integers(0, 2)), float(rng.uniform(0.001, 1)), box, image))
    return preds, truths


