"""Box geometry checks: letterbox mapping and result conversion.
Test generated by Claude Sonnet 5.5
"""

import numpy as np
import pytest
import torch
from ultralytics.data.augment import LetterBox
from ultralytics.engine.results import Results
from ultralytics.utils.ops import scale_boxes

from yolo_lesion_47041585.predict import detections_from_result

IMGSZ = 640


def _foreground_box(image: np.ndarray) -> tuple[float, float, float, float]:
    """Pixel (x1, y1, x2, y2) of the bright rectangle; padding (114) is excluded."""
    ys, xs = np.where(image[..., 0] > 200)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


@pytest.mark.parametrize(
    "shape, box",
    [
        ((1000, 1500), (300, 200, 900, 700)),  # landscape, interior box
        ((1500, 1000), (100, 400, 800, 1100)),  # portrait, interior box
        ((1000, 1500), (0, 0, 400, 300)),  # touches the top-left corner
        ((1000, 1500), (1100, 600, 1500, 1000)),  # touches the bottom-right corner
    ],
)
def test_resize_and_pad_round_trip(shape, box):
    """A box drawn on the original, letterboxed, then mapped back, lands where it began."""
    height, width = shape
    x1, y1, x2, y2 = box
    original = np.zeros((height, width, 3), np.uint8)
    original[y1:y2, x1:x2] = 255

    letterboxed = LetterBox((IMGSZ, IMGSZ))(image=original)
    assert letterboxed.shape[:2] == (IMGSZ, IMGSZ)

    found = torch.tensor([_foreground_box(letterboxed)], dtype=torch.float32)
    restored = scale_boxes((IMGSZ, IMGSZ), found, (height, width))[0]

    # one letterboxed pixel covers ~2.3 original pixels here, so allow a few
    assert restored.tolist() == pytest.approx(list(box), abs=3)


def test_result_conversion_is_normalised_by_the_original_size():
    """A box on a non-square image is normalised by that image's own width and height."""
    height, width = 400, 800
    # x1, y1, x2, y2, confidence, class
    raw = torch.tensor([[200.0, 100.0, 600.0, 300.0, 0.8, 1.0]])
    result = Results(
        np.zeros((height, width, 3), np.uint8),
        path="/data/ISIC_0000123.jpg",
        names={0: "Benign", 1: "Malignant"},
        boxes=raw,
    )

    (detection,) = detections_from_result(result)
    assert detection.image_id == "ISIC_0000123"
    box = detection.box
    assert (box.x_center, box.y_center) == pytest.approx((0.5, 0.5))
    assert (box.width, box.height) == pytest.approx((0.5, 0.5))
    assert detection.class_id == 1
    assert detection.confidence == pytest.approx(0.8)


def test_result_without_boxes_gives_no_detections():
    result = Results(
        np.zeros((100, 100, 3), np.uint8),
        path="ISIC_1.jpg",
        names={0: "Benign", 1: "Malignant"},
        boxes=torch.zeros((0, 6)),
    )
    assert detections_from_result(result) == []
