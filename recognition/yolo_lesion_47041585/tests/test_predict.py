@pytest.fixture(scope="module")
def trained(tmp_path_factory: pytest.TempPathFactory) -> Iterator[tuple[Path, Path]]:
    """A tiny finished run's best checkpoint, and a folder of its unlabelled val images."""
    root = tmp_path_factory.mktemp("trained")
    with pytest.MonkeyPatch.context() as patch:
        patch.chdir(root)  # runs/ is created under the current directory
        config = tiny_config(root, "a0")
        run_dir = run_experiment(config)

    images = root / "unlabelled"
    images.mkdir()
    for image in sorted((root / "data" / "images" / "val").iterdir()):
        shutil.copy(image, images / image.name)
    yield root / run_dir / "weights" / "best.pt", images


def test_load_run_reads_the_settings_saved_with_the_run(trained: tuple[Path, Path]):
    _, settings = load_run(trained[0])
    assert settings.class_names == ("Benign", "Malignant")
    assert (settings.imgsz, settings.conf, settings.iou, settings.max_det) == (
        64, 0.001, 0.7, 100
    )  # fmt: skip


def test_load_run_needs_the_saved_config(trained: tuple[Path, Path], tmp_path: Path):
    stray = tmp_path / "weights" / "best.pt"
    stray.parent.mkdir()
    shutil.copy(trained[0], stray)
    with pytest.raises(FileNotFoundError):
        load_run(stray)


def test_predictions_are_normalised_boxes_without_any_labels(trained: tuple[Path, Path]):
    checkpoint, images = trained
    model, settings = load_run(checkpoint)
    paths = sorted(images.iterdir())
    assert not list(images.glob("*.txt"))  # no labels available

    detections = predict_cases(model, paths, settings, device="cpu")

    assert {d.image_id for d in detections} <= {p.stem for p in paths}
    for d in detections:
        box = d.box
        assert d.class_id in (0, 1)
        assert settings.conf <= d.confidence <= 1
        assert 0 <= box.x_center - box.width / 2 and box.x_center + box.width / 2 <= 1.001
        assert 0 <= box.y_center - box.height / 2 and box.y_center + box.height / 2 <= 1.001
    per_image = [sum(d.image_id == p.stem for d in detections) for p in paths]
    assert max(per_image) <= settings.max_det


def test_command_works_from_a_fresh_process(trained: tuple[Path, Path], tmp_path: Path):
    """The saved checkpoint reloads in a new process and writes boxes and overlays."""
    checkpoint, images = trained
    output = tmp_path / "predictions"
    subprocess.run(
        [sys.executable, "-m", "yolo_lesion_47041585.predict",
         "--checkpoint", str(checkpoint), "--images", str(images),
         "--output", str(output), "--device", "cpu"],
        check=True, capture_output=True,
    )  # fmt: skip

    with (output / "detections.csv").open() as file:
        header = next(csv.reader(file))
    assert header[:5] == ["image_id", "x_center", "y_center", "width", "height"]
    assert len(list((output / "overlays").glob("*.jpg"))) == len(list(images.iterdir()))


