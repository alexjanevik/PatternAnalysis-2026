from pathlib import Path
from typing import Any

import pytest

from yolo_lesion_47041585.train import resolve_training_config

CONFIGS = Path(__file__).resolve().parents[1] / "configs"


def resolve(condition: str) -> dict[str, Any]:
    return resolve_training_config([CONFIGS / "base.yaml", CONFIGS / f"{condition}.yaml"])


def flatten(config: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    flat: dict[str, Any] = {}
    for key, value in config.items():
        name = f"{prefix}{key}"
        if isinstance(value, dict):
            flat.update(flatten(value, f"{name}."))  # pyright: ignore[reportUnknownArgumentType]
        else:
            flat[name] = value
    return flat


def differences(a: str, b: str) -> set[str]:
    """Settings that differ between two conditions, ignoring the condition name."""
    first, second = flatten(resolve(a)), flatten(resolve(b))
    keys = first.keys() | second.keys()
    return {key for key in keys if first.get(key) != second.get(key)} - {"condition"}


@pytest.mark.parametrize("a, b", [("a0", "o35"), ("a0", "o50"), ("o35", "o50")])
def test_oversampling_contrasts_change_only_the_malignant_fraction(a: str, b: str):
    assert differences(a, b) == {"sampling.malignant_fraction"}


def test_b0_is_a_reference_that_differs_in_two_settings():
    """B0 vs A0 changes augmentation and the sampling scheme, so it is not a clean contrast."""
    changed = differences("b0", "a0")
    assert "sampling.scheme" in changed
    assert any(key.startswith("augment.") for key in changed)
    assert not any(key.startswith(("train.", "inference.")) for key in changed)


def test_the_stock_scheme_cannot_have_a_malignant_fraction(tmp_path: Path):
    override = tmp_path / "bad.yaml"
    override.write_text("sampling:\n  scheme: stock\n  malignant_fraction: 0.35\n")
    with pytest.raises(ValueError):
        resolve_training_config([CONFIGS / "base.yaml", override])


