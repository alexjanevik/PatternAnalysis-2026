"""Detection-matching sanity cases.
Test generated by Claude Sonnet 5.5
"""

import pytest

from yolo_lesion_47041585.dataset import NormalizedBox
from yolo_lesion_47041585.helpers.evaluation import box_iou, match_detections
from yolo_lesion_47041585.predict import Detection


def det(
    x: float = 0.5,
    y: float = 0.5,
    w: float = 0.4,
    h: float = 0.4,
    cls: int = 1,
    conf: float = 0.9,
    image: str = "ISIC_1",
) -> Detection:
    return Detection(image, NormalizedBox(x, y, w, h), cls, conf)


def test_iou_known_values():
    box = NormalizedBox(0.5, 0.5, 0.4, 0.4)
    assert box_iou(box, box) == pytest.approx(1.0)
    assert (
        box_iou(NormalizedBox(0.1, 0.5, 0.1, 0.4), NormalizedBox(0.9, 0.5, 0.1, 0.4))
        == 0.0
    )
    # shifted 0.2 along x: intersection 0.2*0.4, union 2*0.16 - 0.08
    assert box_iou(box, NormalizedBox(0.7, 0.5, 0.4, 0.4)) == pytest.approx(1 / 3)


def test_perfect_prediction_matches():
    result = match_detections([det()], [det(conf=1.0)])
    assert len(result.matches) == 1
    assert not result.false_positives and not result.misses


def test_duplicate_prediction_matches_once():
    """Two boxes on one lesion: one match, one false positive."""
    strong, weak = det(conf=0.9), det(x=0.52, conf=0.4)
    result = match_detections([weak, strong], [det(conf=1.0)])
    assert [m[0] for m in result.matches] == [strong]  # highest confidence wins
    assert result.false_positives == (weak,)
    assert not result.misses


def test_wrong_class_is_not_a_match():
    """Right box, wrong class counts as a miss."""
    result = match_detections([det(cls=0)], [det(cls=1, conf=1.0)])
    assert not result.matches
    assert len(result.false_positives) == 1
    assert len(result.misses) == 1


def test_low_iou_is_not_a_match():
    """IoU below 0.5 counts as a miss."""
    result = match_detections([det(x=0.7)], [det(conf=1.0)])  # IoU = 1/3
    assert not result.matches
    assert len(result.false_positives) == 1
    assert len(result.misses) == 1


def test_iou_threshold_is_inclusive():
    result = match_detections([det(x=0.7)], [det(conf=1.0)], iou_threshold=1 / 3 - 1e-9)
    assert len(result.matches) == 1


def test_no_predictions():
    """Every ground-truth box is missed; no error."""
    truths = [det(conf=1.0), det(image="ISIC_2", conf=1.0)]
    result = match_detections([], truths)
    assert not result.matches and not result.false_positives
    assert result.misses == tuple(truths)


def test_boxes_only_match_within_the_same_image():
    result = match_detections([det(image="ISIC_2")], [det(image="ISIC_1", conf=1.0)])
    assert not result.matches
    assert len(result.false_positives) == 1 and len(result.misses) == 1
