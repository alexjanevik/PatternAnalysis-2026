def test_seed_option_replaces_the_config_seed_and_names_the_run(
    monkeypatch: pytest.MonkeyPatch,
):
    seen: list[dict[str, Any]] = []

    def record(config: Any) -> Path:
        seen.append(dict(config))
        return Path(run_id(config))

    monkeypatch.setattr("yolo_lesion_47041585.train.run_experiment", record)
    base = ["--config", str(CONFIGS / "base.yaml"), "--config", str(CONFIGS / "a0.yaml")]

    assert main(base) == 0
    assert main([*base, "--seed", "47041587"]) == 0

    assert [c["seed"] for c in seen] == [47041585, 47041587]
    assert [run_id(c) for c in seen] == ["A0-s47041585", "A0-s47041587"]
    # nothing else about the run changes
    assert {**seen[0], "seed": 0} == {**seen[1], "seed": 0}


def tiny_config(root: Path, condition: str) -> dict[str, Any]:
    """A real condition config pointed at a tiny CPU dataset and a local checkpoint."""
    classes = make_classes(24, 6)
    manifest = root / "split_manifest.csv"
    manifest.write_text(
        "isic_id,split,group_id,class_id\n"
        + "".join(f"{i},train,G{i},{c}\n" for i, c in classes.items())
    )
    checkpoint = root / "detector.pt"
    YOLO("yolo11n.yaml").save(checkpoint)  # built from the config, so no download

    config = resolve_training_config(
        [CONFIGS / "base.yaml", CONFIGS / f"{condition}.yaml"]
    )
    config.update(
        model=str(checkpoint),
        data=str(write_dataset(root / "data", classes)),
        split_manifest=str(manifest),
    )
    config["train"].update(
        epochs=2, imgsz=64, batch=8, nbs=8, workers=0, device="cpu", amp=False
    )
    return config


def test_run_experiment_saves_provenance_results_and_sampling(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    monkeypatch.chdir(tmp_path)  # runs/ is created under the current directory
    config = tiny_config(tmp_path, "o35")

    run_dir = run_experiment(config)

    assert run_dir == Path("runs/O35-s47041585")
    assert yaml.safe_load((run_dir / "config.resolved.yaml").read_text()) == config

    metadata = json.loads((run_dir / "metadata.json").read_text())
    assert metadata["seed"] == 47041585 and metadata["condition"] == "O35"
    assert len(metadata["split_manifest"]["sha256"]) == 64
    assert len(metadata["starting_checkpoint"]["sha256"]) == 64
    assert metadata["environment"]["ultralytics"]

    result = json.loads((run_dir / "result.json").read_text())
    assert result["epochs_run"] == 2
    assert len(result["epoch_seconds"]) == len(result["validation_seconds"]) == 2
    assert all(
        0 <= val <= epoch
        for val, epoch in zip(result["validation_seconds"], result["epoch_seconds"])
    )
    assert (run_dir / result["best_checkpoint"]).exists()  # relative to the run folder
    assert result["batches_per_epoch"] == 4  # 30 images in batches of 8
    assert result["gradient_accumulation"] == 1

    with (run_dir / "sampling.csv").open() as file:
        rows = list(csv.DictReader(file))
    assert [int(row["epoch"]) for row in rows] == [0, 1]
    assert all(int(row["draws"]) == 30 for row in rows)


